/* Rebuild the small home-page index from the authoritative vocabulary, without editing it. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const {resolveSite} = require('./site-path');

function buildVocabIndex(site = resolveSite(), dataDir = path.join(site, 'data')) {
  const context = {window: {}};
  vm.runInNewContext(fs.readFileSync(path.join(dataDir, 'vocab-levels.js'), 'utf8'), context);
  vm.runInNewContext(fs.readFileSync(path.join(site, 'data/learn.js'), 'utf8'), context);
  const bank = context.window.IELTS_BANK;
  const words = {}, previews = {};
  for (const [level, items] of Object.entries(bank.vocabLevels)) {
    words[level] = items.map(item => item.w);
    const preview = items.find(item => item.w.length >= 6 && item.w.length <= 9) || items[0];
    previews[level] = {w: preview.w, zh: preview.zh || preview.meaning || ''};
  }
  const fallback = bank.learn.vocab;
  const preview = fallback.find(item => item.w.length >= 6 && item.w.length <= 9) || fallback[0];
  words.fallback = fallback.map(item => item.w);
  previews.fallback = {w: preview.w, zh: preview.zh || preview.meaning || ''};
  return '/* Generated by node tools/build-vocab-index.js. */\nwindow.IELTS_BANK = window.IELTS_BANK || {};\nwindow.IELTS_BANK.vocabIndex = ' + JSON.stringify({words, previews}) + ';\n';
}
if (require.main === module) {
  const target = path.join(resolveSite(), 'data/vocab-index.js');
  fs.writeFileSync(target, buildVocabIndex());
  console.log(`Generated ${target} (${fs.statSync(target).size} bytes)`);
}
module.exports = {buildVocabIndex};
